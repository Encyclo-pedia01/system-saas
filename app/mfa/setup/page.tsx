import type { Metadata } from 'next';
import { redirect } from 'next/navigation';

import { SetupAuthenticatorForm } from '@/components/auth/mfa-forms';
import { GlassCard } from '@/components/ui/glass-card';
import { requireViewer } from '@/lib/auth/viewer';
import { createAdminClient } from '@/lib/supabase/admin';
import { createClient } from '@/lib/supabase/server';

export const metadata: Metadata = {
  title: 'Set up sign-in codes',
  description: 'Add an authenticator app to protect your school account.',
};

// The auth service may return the QR code as raw SVG markup or as a data URI. Both become an image source.
function qrImageSource(value: string): string {
  if (value.startsWith('data:')) return value;
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(value)}`;
}

export default async function MfaSetupPage() {
  const viewer = await requireViewer();

  if (viewer.role !== 'owner' || viewer.isSuperAdmin || viewer.impersonation) redirect('/dashboard');
  if (viewer.assuranceLevel === 'aal2') redirect('/dashboard');
  if (viewer.mfaEnrolled) redirect('/mfa/verify');

  const supabase = await createClient();

  // Remove any half-finished set-up from an earlier visit (the user's own list only shows
  // confirmed factors), then start a fresh one.
  const admin = createAdminClient();
  const { data: allFactors } = await admin.auth.admin.mfa.listFactors({ userId: viewer.userId });
  for (const factor of allFactors?.factors ?? []) {
    if (factor.status === 'unverified') {
      await admin.auth.admin.mfa.deleteFactor({ id: factor.id, userId: viewer.userId });
    }
  }

  const { data: enrolled, error } = await supabase.auth.mfa.enroll({
    factorType: 'totp',
    friendlyName: 'Campus Veritas',
  });

  return (
    <main className="relative flex flex-1 items-center justify-center px-6 py-16">
      <GlassCard className="w-full max-w-md p-8 sm:p-10">
        <p className="text-xs font-semibold uppercase tracking-[0.2em] text-[var(--accent-soft)]">Owner security</p>
        <h1 className="mt-2 text-2xl font-bold tracking-tight sm:text-3xl">Set up sign-in codes</h1>

        {error || !enrolled ? (
          <p role="alert" className="form-error mt-4">Sign-in codes could not be set up. Refresh the page and try again.</p>
        ) : (
          <>
            <p className="mb-6 mt-2 text-sm leading-relaxed text-[var(--muted)]">
              School owner accounts need a 6-digit code from an authenticator app, such as Google Authenticator, Microsoft Authenticator, or Authy.
            </p>
            <ol className="mb-6 list-decimal space-y-2 pl-5 text-sm text-[var(--muted)]">
              <li>Open your authenticator app and scan this code.</li>
              <li>If you can&apos;t scan it, enter the setup key instead.</li>
              <li>Type the 6-digit code the app shows to confirm.</li>
            </ol>
            <div className="mb-6 flex flex-col items-center gap-4">
              {/* The QR code is an SVG data URI generated by the auth service. */}
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img src={qrImageSource(enrolled.totp.qr_code)} alt="Authenticator setup QR code" width={192} height={192} className="rounded-lg bg-white p-2" />
              <p className="text-xs text-[var(--muted)]">Setup key</p>
              <code className="break-all rounded-md bg-[var(--hover)] px-3 py-2 text-sm">{enrolled.totp.secret}</code>
            </div>
            <SetupAuthenticatorForm factorId={enrolled.id} />
          </>
        )}
      </GlassCard>
    </main>
  );
}
